"""
Decode Packet Tracer PDUs (IPC data type 16) into labelled headers.

PT serializes a frame as its outermost header name, then `16 <inner name>` for each nested header, then every
header's typed fields innermost-first, each header in the order its Java `*Impl.read()` consumes them. Field
names come from data/pdu_fields_<ver>.json, generated by analysis/tools/build_pdu_fields.py.
"""

import json
from functools import lru_cache
from importlib import resources
from typing import Any

from pt_mcp.ptmp import Data

ETHER_TYPES = {2048: "IPv4", 2054: "ARP", 34525: "IPv6", 33024: "802.1Q"}
IP_PROTOCOLS = {1: "ICMP", 2: "IGMP", 6: "TCP", 17: "UDP", 47: "GRE", 50: "ESP", 58: "ICMPv6", 88: "EIGRP", 89: "OSPF"}
ICMP_TYPES = {0: "echo-reply", 3: "destination-unreachable", 5: "redirect", 8: "echo-request", 11: "time-exceeded"}
ARP_OPS = {1: "request", 2: "reply"}
FIELD_LABELS = {
    ("EthernetIIHeader", "frameType"): ETHER_TYPES,
    ("Dot1qHeader", "typeLength"): ETHER_TYPES,
    ("IpHeader", "protocol"): IP_PROTOCOLS,
    ("IcmpMessage", "icmpType"): ICMP_TYPES,
    ("ArpPacket", "usOperation"): ARP_OPS,
}


@lru_cache(maxsize=4)
def field_table(name: str = "pdu_fields_9.0.1.json") -> dict[str, list[str]]:
    return json.loads(resources.files("pt_mcp.data").joinpath(name).read_text())


def _typed(tokens: list[str], i: int) -> tuple[Any, int]:
    """Read one tagged value (type code, then value tokens) starting at tokens[i]."""
    return _value(tokens, i + 1, int(tokens[i]))


def _value(tokens: list[str], i: int, t: int) -> tuple[Any, int]:
    """Read an untagged value of type t starting at tokens[i]; returns (value, next index)."""
    if t == 0:
        return None, i
    if t == 2:
        return tokens[i].lower() == "true", i + 1
    if t == 1:
        return int(tokens[i]) & 0xFF, i + 1  # PT sends bytes signed (e.g. HDLC address 0x8F as -113)
    if t in (3, 4, 5):
        return int(tokens[i]), i + 1
    if t in (6, 7):
        return float(tokens[i]), i + 1
    if t == 14:
        a, i = _typed(tokens, i)
        b, i = _typed(tokens, i)
        return [a, b], i
    if t == 15:
        sub, n, i = int(tokens[i]), int(tokens[i + 1]), i + 2
        out = []
        for _ in range(n):
            item, i = _value(tokens, i, sub)
            out.append(item)
        return out, i
    if t == 16:
        return {"data": tokens[i]}, i + 1
    return tokens[i], i + 1


def decode(value: Any, table: dict[str, list[str]] | None = None) -> list[dict]:
    """Return [{"header": name, "fields": {...}}, ...] outermost first. Unknown trailing tokens go to "unparsed"."""
    if not isinstance(value, Data):
        return []
    table = table or field_table()
    tokens = value.fields
    names, i = [value.subtype], 0
    while i + 1 < len(tokens) and tokens[i] == "16":
        names.append(tokens[i + 1])
        i += 2
    headers = [{"header": n, "fields": {}} for n in names]
    try:
        for h in reversed(headers):
            for field in table.get(h["header"], []):
                if i >= len(tokens):
                    break
                v, i = _typed(tokens, i)
                labels = FIELD_LABELS.get((h["header"], field))
                h["fields"][field] = f"{v} ({labels[v]})" if labels and v in labels else v
    except (ValueError, IndexError):
        pass
    if i < len(tokens):
        headers[0]["fields"]["unparsed"] = tokens[i:]
    return headers
